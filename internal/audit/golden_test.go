func TestFixTextAndReportTextNonEmpty(t *testing.T) {
	m := mustModel(t, "sample-show-config.txt")
	findings, err := Run(m)
	if err != nil {
		t.Fatal(err)
	}
	if fix := FixText(findings); len(fix) == 0 || !contains(fix, "proposed fixes") {
		t.Error("FixText: expected header missing")
	}
	if report := ReportText(findings, m); !contains(report, "SRX HARDENING AUDIT") ||
		!contains(report, "Detected source format: curly") {
		t.Error("ReportText: expected structure missing")
	}
}

func contains(s, sub string) bool {
	for i := 0; i+len(sub) <= len(s); i++ {
		if s[i:i+len(sub)] == sub {
			return true
		}
	}
	return false
}
